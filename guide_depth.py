def extra_guide(slug,titles):
    d=EXTRAS[slug]
    body='<h2>'+E(d['heading'])+'</h2><p>'+E(d['intro'])+'</p>'
    body+='<div class="table-wrap"><table><thead><tr>'+''.join('<th scope="col">'+E(x)+'</th>' for x in d['headers'])+'</tr></thead><tbody>'+''.join('<tr>'+''.join('<td>'+E(v)+'</td>' for v in row)+'</tr>' for row in d['rows'])+'</tbody></table></div>'
    body+='<h2>'+E(d.get('secondHeading','怎样把表中的条件落实到选择'))+'</h2><p>'+E(d['analysis'])+'</p>'
    body+='<h2>'+E(d.get('checkHeading','本页操作清单'))+'</h2><ol>'+''.join('<li>'+E(x)+'</li>' for x in d['check'])+'</ol>'
    if d.get('source'):
        url,label=d['source'];body+='<p class="meta">方法资料：<a href="'+E(url)+'" target="_blank" rel="noopener noreferrer">'+E(label)+'</a>；引用用于理解测量或配置，不作为品牌体验证据。</p>'
