import assert from 'node:assert/strict';
import fs from 'node:fs';
import {matchPlan,candidatePool} from './assets/comparison-core.mjs';
const brands=JSON.parse(fs.readFileSync(new URL('./dist/assets/compare-data.json',import.meta.url),'utf8'));
const byId=Object.fromEntries(brands.map(b=>[b.id,b]));
assert.equal(brands.length,29);
assert.deepEqual(matchPlan(byId.breezenet,200,30),{status:'matched',plan:byId.breezenet.plans[0],remaining:0,cost:0.135,withinBudget:true,difference:-3});
assert.equal(matchPlan(byId.flycat,200,30).plan.price,45);
assert.equal(matchPlan(byId.flycat,200,30).withinBudget,false);
assert.equal(matchPlan(byId.breezenet,500,57).remaining,0);
assert.equal(matchPlan(byId.breezenet,500,56.99).withinBudget,false);
assert.equal(matchPlan(byId.breezenet,2000,100000).status,'uncovered');
assert.equal(matchPlan(byId.breezenet,0,30).status,'invalid');
assert.equal(matchPlan(byId.breezenet,NaN,30).status,'invalid');
assert.equal(matchPlan(byId.breezenet,200,-1).status,'invalid');
for(const id of ['firefly','jilian','kosing'])assert.equal(matchPlan(byId[id],1,100000).status,'excluded');
assert.equal(candidatePool(brands,200,30,'report',false).length,11);
assert.equal(candidatePool(brands,200,30,'dated',false).length,10);
assert.equal(candidatePool(brands,200,0,'all',true).length,0);
const affordable=candidatePool(brands,200,30,'all',true);
assert(affordable.some(b=>b.id==='breezenet'));
assert(!affordable.some(b=>b.id==='flycat'));
assert(!affordable.some(b=>b.id==='firefly'));
assert.equal(matchPlan({eligible:true,plans:[{gb:1000,price:50},{gb:200,price:20}]},200,30).plan.price,20);
console.log(JSON.stringify({comparison:'passed',brands:brands.length,datedReports:10,undatedReports:1,excluded:3,affordableAt200GB:affordable.length}));
